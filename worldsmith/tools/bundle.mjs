/* Worldsmith - single-file build.
 *
 *   node worldsmith/tools/bundle.mjs
 *
 * Inlines styles.css and every script into one self-contained HTML file at
 * dist/worldsmith.html, which can be opened by double-clicking with no server,
 * no install and no dependencies.
 *
 * The load order is parsed out of index.html rather than hardcoded here: it is
 * dependency-ordered and load-bearing (terrain before grid, species before
 * units), and a second copy of that list would drift. */

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const root = path.resolve(here, '..');
const outDir = path.join(root, 'dist');
const outFile = path.join(outDir, 'worldsmith.html');

const html = fs.readFileSync(path.join(root, 'index.html'), 'utf8');

/* A literal </script> inside a string or comment would close the tag early and
 * break the page, so neutralise it. The escaped form is equivalent in JS. */
function safe(js) {
  return js.replace(/<\/script>/gi, '<\\/script>');
}

let scriptCount = 0;
let cssCount = 0;

let out = html
  .replace(/[ \t]*<link rel="stylesheet" href="([^"]+)"\s*\/?>/g, (_, href) => {
    const css = fs.readFileSync(path.join(root, href), 'utf8');
    cssCount++;
    return `<style>\n${css}\n</style>`;
  })
  .replace(/[ \t]*<script src="([^"]+)"><\/script>/g, (_, src) => {
    const js = fs.readFileSync(path.join(root, src), 'utf8');
    scriptCount++;
    return `<script>\n/* ---- ${src} ---- */\n${safe(js)}\n</script>`;
  });

if (cssCount !== 1) throw new Error(`Expected 1 stylesheet, inlined ${cssCount}`);
if (scriptCount < 30) throw new Error(`Only inlined ${scriptCount} scripts - index.html changed shape?`);

/* Nothing may be left pointing at the filesystem. */
const leftover = out.match(/(?:src|href)="(?!data:|https?:|#)[^"]+"/g);
if (leftover) throw new Error(`Bundle still references external files: ${leftover.join(', ')}`);

const banner = `<!--
  Worldsmith - single-file build, generated by tools/bundle.mjs.
  Everything is inlined: no server, no install, no dependencies. Just open it.
  Edit the sources in worldsmith/src and re-run the bundler; do not edit this file.
-->
`;
out = out.replace(/^<!doctype html>\r?\n/i, (m) => m + banner);

fs.mkdirSync(outDir, { recursive: true });
fs.writeFileSync(outFile, out);

const kb = (fs.statSync(outFile).size / 1024).toFixed(0);
console.log(
  `Bundled ${scriptCount} scripts + ${cssCount} stylesheet into ${path.relative(process.cwd(), outFile)} (${kb} KB)`
);
